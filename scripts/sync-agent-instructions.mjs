#!/usr/bin/env node
/**
 * sync-agent-instructions — one source of truth, many agent tools.
 *
 * Humans edit only:
 *   - AGENTS.md                     tool-agnostic project guidance
 *   - .claude/skills/<name>/SKILL.md   Claude skills
 *
 * This script (re)generates the GitHub Copilot equivalents, which have no
 * "include" mechanism of their own:
 *   - .github/copilot-instructions.md          <- whole of AGENTS.md
 *   - .github/instructions/<slug>.instructions.md  <- one per AGENTS.md section
 *         that carries a `<!-- copilot:applyTo=<glob>[,<glob>] -->` marker
 *   - .github/prompts/<name>.prompt.md         <- one per Claude skill
 *
 * CLAUDE.md is static: it `@AGENTS.md`-imports the source, so Claude needs
 * nothing generated.
 *
 * Usage:
 *   node scripts/sync-agent-instructions.mjs           # write the generated files
 *   node scripts/sync-agent-instructions.mjs --check   # exit 1 if anything is stale (CI)
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, statSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const SENTINEL = 'GENERATED by scripts/sync-agent-instructions.mjs — do not edit';
const APPLY_RE = /^<!--\s*copilot:applyTo=([^>]+?)\s*-->\s*$/;

/** Collected {path, content} outputs plus the set of paths we own. */
const outputs = [];
const owned = new Set();

function emit(relPath, content) {
  outputs.push({ relPath, content });
  owned.add(relPath);
}

// ---------------------------------------------------------------------------
// 1. Parse AGENTS.md into top-level (`## `) sections.
// ---------------------------------------------------------------------------
const agentsPath = join(ROOT, 'AGENTS.md');
if (!existsSync(agentsPath)) {
  console.error('AGENTS.md not found at repo root — nothing to sync.');
  process.exit(1);
}
const agentsRaw = readFileSync(agentsPath, 'utf8').replace(/\r\n/g, '\n');

/** @type {{heading:string, level:number, applyTo:string[], body:string}[]} */
const sections = [];
let cur = null;
for (const line of agentsRaw.split('\n')) {
  const h = /^(#{1,3})\s+(.*)$/.exec(line);
  if (h) {
    cur = { heading: h[2].trim(), level: h[1].length, applyTo: [], body: '' };
    sections.push(cur);
    continue;
  }
  if (!cur) continue;
  const m = APPLY_RE.exec(line.trim());
  if (m) {
    cur.applyTo.push(...m[1].split(',').map((s) => s.trim()).filter(Boolean));
    continue; // marker lines never reach the output
  }
  cur.body += line + '\n';
}

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/`/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

// ---------------------------------------------------------------------------
// 2. .github/copilot-instructions.md  = banner + full AGENTS.md (markers stripped)
// ---------------------------------------------------------------------------
const strippedAgents = agentsRaw
  .split('\n')
  .filter((l) => !APPLY_RE.test(l.trim()))
  .join('\n')
  .trim();

emit(
  '.github/copilot-instructions.md',
  `<!-- ${SENTINEL}. Source: AGENTS.md -->\n\n${strippedAgents}\n`,
);

// ---------------------------------------------------------------------------
// 3. .github/instructions/<slug>.instructions.md  — one per marked section
// ---------------------------------------------------------------------------
for (const s of sections) {
  if (s.applyTo.length === 0) continue;
  const name = `${slug(s.heading)}.instructions.md`;
  const applyTo = s.applyTo.length === 1 ? s.applyTo[0] : `{${s.applyTo.join(',')}}`;
  emit(
    join('.github/instructions', name),
    `---\napplyTo: "${applyTo}"\n---\n<!-- ${SENTINEL}. Source: AGENTS.md › "${s.heading}" -->\n\n` +
      `## ${s.heading}\n${s.body.trimEnd()}\n`,
  );
}

// ---------------------------------------------------------------------------
// 4. .github/prompts/<name>.prompt.md  — one per Claude skill
// ---------------------------------------------------------------------------
const skillsDir = join(ROOT, '.claude/skills');
if (existsSync(skillsDir)) {
  for (const entry of readdirSync(skillsDir)) {
    const skillMd = join(skillsDir, entry, 'SKILL.md');
    if (!existsSync(skillMd) || !statSync(skillMd).isFile()) continue;
    const raw = readFileSync(skillMd, 'utf8').replace(/\r\n/g, '\n');
    const fm = /^---\n([\s\S]*?)\n---\n?/.exec(raw);
    const meta = {};
    if (fm) {
      for (const l of fm[1].split('\n')) {
        const kv = /^([a-zA-Z0-9_-]+):\s*(.*)$/.exec(l);
        if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
      }
    }
    const name = meta.name || entry;
    const description = meta.description || `Run the ${name} workflow.`;
    const body = fm ? raw.slice(fm[0].length).trim() : raw.trim();
    emit(
      join('.github/prompts', `${name}.prompt.md`),
      `---\nmode: agent\ndescription: "${description.replace(/"/g, "'")}"\n---\n` +
        `<!-- ${SENTINEL}. Source: .claude/skills/${entry}/SKILL.md -->\n\n${body}\n`,
    );
  }
}

// ---------------------------------------------------------------------------
// 5. Reconcile with disk.
// ---------------------------------------------------------------------------
function listGenerated(dir) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs)
    .map((f) => join(dir, f))
    .filter((rel) => {
      const p = join(ROOT, rel);
      return statSync(p).isFile() && readFileSync(p, 'utf8').includes(SENTINEL);
    });
}

const stale = [
  ...listGenerated('.github/instructions'),
  ...listGenerated('.github/prompts'),
].filter((rel) => !owned.has(rel));

let drift = 0;
for (const { relPath, content } of outputs) {
  const abs = join(ROOT, relPath);
  const existing = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (existing === content) continue;
  drift++;
  if (CHECK) {
    console.log(`${existing === null ? 'missing' : 'stale  '}  ${relPath}`);
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`${existing === null ? 'created' : 'updated'}  ${relPath}`);
  }
}
for (const rel of stale) {
  drift++;
  if (CHECK) console.log(`orphan   ${rel}`);
  else {
    rmSync(join(ROOT, rel));
    console.log(`removed  ${rel}`);
  }
}

if (CHECK && drift) {
  console.error(`\n${drift} file(s) out of sync — run: npm run sync:agents`);
  process.exit(1);
}
console.log(CHECK ? '\nagent instructions are in sync' : `\ndone (${drift || 'no'} change${drift === 1 ? '' : 's'})`);
