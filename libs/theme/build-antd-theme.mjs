/**
 * Compiles ng-zorro-antd's Less with the design tokens injected as Less
 * variable overrides (`modifyVars`), producing two brand-skinned stylesheets:
 *
 *   generated/antd.css        light baseline  (unscoped)
 *   generated/antd-dark.css   dark overrides, scoped under [data-theme="dark"]
 *
 * Why a dedicated step instead of letting the Angular builder compile the
 * Less: Ant Design v4's `colorPalette.less` uses inline JavaScript, which
 * needs `javascriptEnabled: true` — an option the Angular/esbuild Less
 * pipeline does not expose. Compiling here keeps the "tokens drive the
 * ng-zorro Less variables" contract intact for every consumer.
 *
 * Runtime brand switching (brand-1 <-> brand-2 <-> brand-3) still happens purely through
 * the CSS custom properties in `@brand/tokens/css`, layered over this
 * baseline; this file only bakes the parts of ng-zorro's chrome that its
 * Less pipeline computes rather than reads from a CSS variable.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const less = require('less');

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const WORKSPACE = path.resolve(ROOT, '../..');
const NODE_MODULES = path.join(WORKSPACE, 'node_modules');
const JSON_DIR = path.join(WORKSPACE, 'libs/tokens/generated/json');
const OUT_DIR = path.join(ROOT, 'generated');

/** ng-zorro / Ant Design v4 Less theme variables <- design tokens. */
function mapVars(t) {
  const c = t.color;
  return {
    'primary-color': c.action.primary,
    'primary-color-hover': c.action['primary-hover'],
    'primary-color-active': c.action['primary-active'],
    'info-color': c.feedback['info-fg'],
    'success-color': c.feedback['success-fg'],
    'warning-color': c.feedback['warning-fg'],
    'error-color': c.feedback['danger-fg'],

    'heading-color': c.text.primary,
    'text-color': c.text.primary,
    'text-color-secondary': c.text.secondary,
    'disabled-color': c.text.disabled,

    'body-background': c.bg.canvas,
    'component-background': c.bg.surface,
    'popover-background': c.bg.surface,
    'layout-body-background': c.bg.canvas,
    'layout-header-background': c.bg.surface,
    'layout-sider-background': c.bg.surface,
    'table-header-bg': c.bg.subtle,
    'item-hover-bg': c.bg.hover,

    'border-color-base': c.border.default,
    'border-color-split': c.border.subtle,
    'border-radius-base': t.radius.md,
    'border-radius-sm': t.radius.sm,

    'font-family': t.font.family.base,
    'code-family': t.font.family.mono,
    'font-size-base': t.font.size.md,
    'font-size-lg': t.font.size.lg,
    'font-size-sm': t.font.size.sm,
    'line-height-base': t.font.lineHeight.normal,

    'height-base': t.size.control.md,
    'height-lg': t.size.control.lg,
    'height-sm': t.size.control.sm,

    'box-shadow-base': t.elevation['2'],
  };
}

async function compile({ entry, tokensFile, wrapSelector, outFile }) {
  const tokens = JSON.parse(await fs.readFile(path.join(JSON_DIR, tokensFile), 'utf8'));
  const importLine = `@import "${NODE_MODULES}/ng-zorro-antd/${entry}";`;
  const input = wrapSelector ? `${wrapSelector} {\n${importLine}\n}` : importLine;

  const started = Date.now();
  let css;
  try {
    ({ css } = await less.render(input, {
      javascriptEnabled: true,
      paths: [NODE_MODULES],
      math: 'parens-division',
      modifyVars: mapVars(tokens),
      filename: outFile,
    }));
  } catch (err) {
    console.error(`\nLess compilation of ${entry} failed:`);
    console.error(err.message ?? err);
    process.exit(1);
  }

  const banner =
    `/* Generated by libs/theme/build-antd-theme.mjs from ${entry}. Do not edit. */\n` +
    `/* Regenerate with: nx run theme:styles */\n`;
  await fs.writeFile(path.join(OUT_DIR, outFile), banner + css, 'utf8');
  const kb = (Buffer.byteLength(css) / 1024).toFixed(0);
  console.log(`✔ generated/${outFile} (${kb} KB) in ${Date.now() - started}ms`);
}

await fs.mkdir(OUT_DIR, { recursive: true });

await compile({
  entry: 'ng-zorro-antd.less',
  tokensFile: 'tokens.json',
  wrapSelector: null,
  outFile: 'antd.css',
});

await compile({
  entry: 'ng-zorro-antd.dark.less',
  tokensFile: 'tokens.dark.json',
  wrapSelector: '[data-theme="dark"]',
  outFile: 'antd-dark.css',
});
